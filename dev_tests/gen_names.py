# 표기가 따로 갈리는 경우 (글자 바꾸기로 만들 수 없는 것)
EXTRA = {
    "佐々木": ["佐佐木"],
    "奈々": ["奈奈"],
    "乃々花": ["乃乃花"],
}

def expand(name):
    opts = [[c] + list(VAR.get(c, "")) for c in name]
    out = []
    for combo in itertools.product(*opts):
        s = "".join(combo)
        if s not in out:
            out.append(s)
    for e in EXTRA.get(name, []):
        if e not in out:
            out.append(e)
    return out

def parse(block):
    for line in block.strip().splitlines():
        line = line.strip()
        if line:
            k, h = line.split()
            yield k, h

sections = [
    ("여성 이름 (이름)", GIVEN_F),
    ("남성 이름 (이름)", GIVEN_M),
    ("성씨", SURNAMES),
]

seen = {}
lines = [
    "# 일본어 이름 치환 규칙 (중국어 자막의 일본어 이름 -> 일본어 발음 한글)",
    "# 형식: 찾을 말<TAB>바꿀 말<TAB>옵션<TAB>탭 이름.  가져오면 '이름만' 탭이 자동으로 만들어져요.",
    "# 한자 하나에 읽기가 여러 가지인 이름은 가장 흔한 읽기 하나만 넣었어요. 다르게 읽는 이름은 규칙 탭에서 고쳐 주세요.",
    "# 일본어 원형 / 중국어 간체 / 번체(이체자 포함)를 모두 같은 읽기로 바꿔요.",
]
count = 0
for title, block in sections:
    lines.append("# ===== " + title + " =====")
    for kanji, hangul in parse(block):
        for form in expand(kanji):
            if form in seen:
                if seen[form] != hangul:
                    sys.exit("충돌: %s -> %s / %s" % (form, seen[form], hangul))
                continue
            seen[form] = hangul
            lines.append("%s\t%s\t\t%s" % (form, hangul, TAB))
            count += 1

open("일본어이름_치환규칙.tsv", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(count, "rules")
