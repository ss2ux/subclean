# -*- coding: utf-8 -*-
# 말투 기본 규칙 팩 생성기: speech_pack.tsv 를 만든다.
# 플래그: R=정규식, H=높임 전용, C=반말 전용.  {받침} 등은 앱(Cleaner)이 글자 묶음으로 풀어 준다.

Q = "[”\"'’」』)\\]]*"
TAG = "(?:</[a-zA-Z]+>)*"
# 문장 끝: (.!?…~ 뒤에 공백/줄 끝) 또는 줄 끝 또는 쉼표
E = "(?=[.!?…~]+" + Q + TAG + "(?:\\s|$)|" + Q + TAG + "\\s*$|[,，])"
NB = "(?<![가-힣])"   # 앞에 한글이 붙어 있지 않음

rules = []   # (find, replace, flags, comment or None)
def sec(title): rules.append((None, None, None, title))
def R(find, repl, flags): rules.append((find, repl, flags, None))

# ================= 높임 (H) : 반말/한다체 -> 해요체 =================
H = "RH"
sec("===== 높임: 나->저 (나 자신을 가리킬 때만. 그러나/나이/나라/나가 는 건드리지 않음) =====")
R(NB + "나(?=는|를|도|만|랑|한테|에게|의|조차|까지|보다|처럼|부터|야말로|[ ,.!?…~]|$)", "저", H)
R(NB + "내(?=가|게| )", "제", H)
R(NB + "(?<!어느 |그 |이 |저 |다른 |좋은 |오는 |어떤 |그런 |이런 |같은 |첫 |마지막 |특별한 |중요한 )날(?= )", "절", H)
R(NB + "난(?=[ ,])", "전", H)
sec("===== 높임: 너 -> 당신 (너무/너희/너머/너구리 는 건드리지 않음) =====")
R(NB + "너야" + E, "당신이에요", H)
R(NB + "너는", "당신은", H)
R(NB + "너를", "당신을", H)
R(NB + "너랑", "당신이랑", H)
R(NB + "너(?=도|만|한테|에게|의|조차|까지|보다|처럼|부터|야말로|[ ,.!?…~]|$)", "당신", H)
R(NB + "넌(?=[ ,])", "당신은", H)
R(NB + "널(?=[ ,])", "당신을", H)
R(NB + "네가(?= )", "당신이", H)
R(NB + "네게(?= )", "당신에게", H)
sec("===== 높임: 인사/대답 =====")
R(NB + "안녕" + E, "안녕하세요", H)
R(NB + "응(?=[ ,.!?…~]|$)", "네", H)
R("^((?:[-–]\\s*)?)야(?=[!?, ])", "$1저기요", H)
sec("===== 높임: ~야 / ~이야 / ~거야 (이다) =====")
R(NB + "나야" + E, "저예요", H)
R(NB + "아니야" + E, "아니에요", H)
R(NB + "아냐" + E, "아니에요", H)
R(NB + "(너|우리|뭐|누구|어디|언제|진짜|정말|사실|농담|장난|거짓말|이거|그거|저거|여기|거기|저기)야" + E, "$1예요", H)
R(NB + "거야" + E, "거예요", H)
R("(?<={ㄹ받침})거야" + E, "거예요", H)
R("(?<={받침})이야" + E, "이에요", H)
R("(?<=[가-힣] [가-힣]{0,7}{무받침})(?<!해|가|와|봐|써|줘|돼|서|어|아)야" + E, "예요", H)
R("(?<={받침})이다" + E, "이에요", H)
R(NB + "아니다" + E, "아니에요", H)
sec("===== 높임: 해/돼/봐/줘/와/가/워 등 줄임 해체 =====")
R("(?<=[가-힣\\s])(?<!올|새|그|매|한|이|지난|이듬|손|피|오|방|공|재|상|유|무|어느 |다음 )해" + E, "해요", H)
R("돼" + E, "돼요", H)
R("봐" + E, "봐요", H)
R("줘" + E, "주세요", H)
R("(?<=[가-힣]\\s)와" + E, "와요", H)
R("(?<=[가-힣]\\s)가" + E, "가요", H)
R("(?<=[가-힣])(?<![우오아타파])워" + E, "워요", H)
R(NB + "(그래|이래|저래|어때|몰라)" + E, "$1요", H)
R("(아파|바빠|나빠|예뻐|기뻐|슬퍼|고파|졸려)" + E, "$1요", H)
sec("===== 높임: 아/어 해체 =====")
R("(?<={ㅆ받침})어" + E, "어요", H)
R("(?<={양성받침})아" + E, "아요", H)
R("(?<={받침})(?<!{양성받침})(?<!국|영|본|일|단|언)어" + E, "어요", H)
sec("===== 높임: 어미별 해체 =====")
R("(?<=[가-힣])거든" + E, "거든요", H)
R("(?<=[가-힣])건데" + E, "건데요", H)
R("(?<=[가-힣])텐데" + E, "텐데요", H)
R("(?<=[가-힣])([는은인])데" + E, "$1데요", H)
R("(?<=[가-힣])잖아" + E, "잖아요", H)
R("(?<={ㄹ받침})(게|까|걸|래)" + E, "$1요", H)
R("(?<=[가-힣])구나" + E, "군요", H)
R("(?<={ㅆ받침})군" + E, "군요", H)
R("(?<=그렇|좋|없|많|같|아니|대단하|멋지|이렇|저렇|괜찮|예쁘|귀엽|재밌)군" + E, "군요", H)
R("(?<=[가-힣])(?<!우리|저희|이모|고모|친구)네" + E, "네요", H)
R("(?<={ㅆ받침})지" + E, "죠", H)
R("(?<=그렇|맞|좋|있|없|알|아니|같|괜찮|싶|이렇|저렇|그러|이러|모르|다르|많|힘들|어렵|쉽)지" + E, "죠", H)
R(NB + "그치" + E, "그쵸", H)
R("(?<=[가-힣])(?<![머아])니(?=[?？])", "나요", H)
R("(?<=[가오하먹보쉬놀듣읽씻앉만나]|{ㄹ받침})자" + E, "죠", H)
R("해라" + E, "하세요", H)
R(NB + "가라" + E, "가세요", H)
R(NB + "와라" + E, "오세요", H)
R(NB + "봐라" + E, "보세요", H)
R("(?<={받침})(?<!{ㄹ받침})[아어]라" + E, "으세요", H)
sec("===== 높임: 한다체(-다) =====")
R("(?<={ㅆ받침})다" + E, "어요", H)
R("(?<=없)다" + E, "어요", H)
R("한다" + E, "해요", H)
R("간다" + E, "가요", H)
R("온다" + E, "와요", H)
R("본다" + E, "봐요", H)
R("준다" + E, "줘요", H)
R("쓴다" + E, "써요", H)
R("된다" + E, "돼요", H)
R("낸다" + E, "내요", H)
R("(?<={양성받침})는다" + E, "아요", H)
R("(?<={받침})(?<!{양성받침})는다" + E, "어요", H)
R("(?<=좋|많|작|높|낮|밝|괜찮|않|맞|알|받|살|앉|닫|막|잡|찾|남|짧|같)다" + E, "아요", H)
R("(?<=먹|읽|믿|웃|죽|넓|멀|길|깊|늦|굵|젊|싫|힘들)다" + E, "어요", H)

# ================= 반말 (C) : 존댓말 -> 해체 =================
C = "RC"
R("저희", "우리", "C")
sec("===== 반말: 저->나 (나 자신을 가리킬 때만. 저 사람/저기 는 건드리지 않음) =====")
R(NB + "저(?=는|를|도|만|랑|한테|에게|의|조차|까지|보다|처럼|부터|야말로)", "나", C)
R(NB + "저예요" + E, "나야", C)
R(NB + "저요" + E, "나", C)
R(NB + "저(?= (?:이제|지금|먼저|좀|정말|진짜|그냥|벌써|아직|오늘|내일|다시|혼자|너무|잠깐|잠시|일단|솔직히|사실|꼭|절대|조금|이따|아까|방금|어제|매일|항상|가끔|바로|곧|계속|잘|못|또|아마|원래)(?![가-힣]))", "나", C)
R(NB + "저(?= [가-힣]{1,4}(?:게요|래요|겠어요|겠습니다|거예요))", "나", C)
R(NB + "제(?=가|게)", "내", C)
R(NB + "제(?= (?![0-9０-９]))", "내", C)
R(NB + "절(?= )", "날", C)
R(NB + "전(?= (?!세계|남[자편친]|여[자친]|애인|직|체|국|문|부|전|통|화|날|번|달|해|주|기|면|총|임))", "난", C)
sec("===== 반말: 인사/대답 (일반 규칙 아님, 안전한 자리만) =====")
R("안녕하세요", "안녕", "C")
R("안녕하십니까", "안녕", "C")
R("안녕히 가세요", "잘 가", "C")
R("안녕히 계세요", "잘 있어", "C")
R("안녕히 주무세요", "잘 자", "C")
R("감사합니다", "고마워", "C")
R("고맙습니다", "고마워", "C")
R("감사해요", "고마워", "C")
R("죄송합니다", "미안해", "C")
R("죄송해요", "미안해", "C")
R("미안합니다", "미안해", "C")
R(NB + "네(?=[,.!?…~]|$)", "응", C)
R(NB + "예(?=[,.!?…~]|$)", "응", C)
R(NB + "아니요", "아니", C)
sec("===== 반말: 합쇼체(-ㅂ니다) =====")
R("(?<={ㅆ받침})습니[다까]" + E, "어", C)
R("(?<={양성받침})(?<!{ㅆ받침})습니[다까]" + E, "아", C)
R("(?<={받침})(?<!{양성받침})(?<!{ㅆ받침})습니[다까]" + E, "어", C)
R("합니[다까]" + E, "해", C)
R("아닙니[다까]" + E, "아니야", C)
R("(?<={받침})입니[다까]" + E, "이야", C)
R("(?<={무받침})입니[다까]" + E, "야", C)
R("갑니[다까]" + E, "가", C)
R("옵니[다까]" + E, "와", C)
R("봅니[다까]" + E, "봐", C)
R("줍니[다까]" + E, "줘", C)
R("씁니[다까]" + E, "써", C)
R("됩니[다까]" + E, "돼", C)
R("갑시다" + E, "가자", C)
R("합시다" + E, "하자", C)
R("봅시다" + E, "보자", C)
R("(?<={받침})읍시다" + E, "자", C)
sec("===== 반말: ~세요 =====")
R("주세요" + E, "줘", C)
R("하세요" + E, "해", C)
R("가세요" + E, "가", C)
R("오세요" + E, "와", C)
R("(?<!여)보세요" + E, "봐", C)
R("드세요" + E, "먹어", C)
R("쓰세요" + E, "써", C)
R("계세요" + E, "있어", C)
R("마세요" + E, "마", C)
R("(?<={양성받침})으세요" + E, "아", C)
R("(?<={받침})으세요" + E, "어", C)
sec("===== 반말: ~이에요 / ~예요 / ~요 =====")
R("아니에요" + E, "아니야", C)
R("이에요" + E, "이야", C)
R("예요" + E, "야", C)
R("(?<=[가-힣])군요" + E, "구나", C)
R("(?<=[가-힣])쵸" + E, "치", C)
R("(?<=[가-힣])죠" + E, "지", C)
R("(?<=[가-힣])나요(?=[?？])", "니", C)
R("(?<=[가-힣])(?<!세|저기|여기|거기)요" + E, "", C)

sec("===== 높임: 마무리 (이미 설치된 앱에 규칙이 끝에 붙어도 결과가 같도록) =====")
R(NB + "너예요" + E, "당신이에요", H)

# ---- 출력 ----
def esc(s): return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")
out = ["# 자막 다듬기 기본 말투 규칙 팩: 찾을 말<TAB>바꿀 말<TAB>옵션(R=정규식, H=높임 전용, C=반말 전용)",
       "# {받침} {무받침} {ㄹ받침} {ㄴ받침} {ㅆ받침} {양성받침} 은 앱이 받침 있는/없는 글자 묶음으로 바꿔서 처리해요.",
       "# 정규식 규칙은 위에서 아래 순서대로 적용되니 순서를 바꾸지 마세요."]
for f, r, fl, c in rules:
    if f is None: out.append("# " + c)
    else: out.append(esc(f) + "\t" + esc(r) + "\t" + fl)
open("speech_pack.tsv", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len([1 for x in rules if x[0]]), "rules")
